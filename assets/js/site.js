function renderGrid(id, items, renderer) {
    const container = document.getElementById(id);
    if (!container) return;
    container.innerHTML = items.map(renderer).join("");
}

function renderPills(items) {
    return items.map((item) => `<span class="pill">${item}</span>`).join("");
}

function setupNavigation() {
    const menuToggle = document.getElementById("menuToggle");
    const navMenu = document.getElementById("siteNav");

    if (menuToggle && navMenu) {
        menuToggle.addEventListener("click", () => {
            const expanded = menuToggle.getAttribute("aria-expanded") === "true";
            menuToggle.setAttribute("aria-expanded", String(!expanded));
            navMenu.classList.toggle("is-open");
        });

        navMenu.querySelectorAll("a").forEach((link) => {
            link.addEventListener("click", () => {
                menuToggle.setAttribute("aria-expanded", "false");
                navMenu.classList.remove("is-open");
            });
        });
    }

    const page = document.body.dataset.page;
    document.querySelectorAll("[data-nav]").forEach((link) => {
        if (link.dataset.nav === page) {
            link.classList.add("is-active");
        }
    });
}

function setupReveal() {
    const revealables = document.querySelectorAll(".reveal");
    const reduceMotion = window.matchMedia("(prefers-reduced-motion: reduce)");

    if (reduceMotion.matches || !("IntersectionObserver" in window)) {
        revealables.forEach((element) => element.classList.add("is-visible"));
        return;
    }

    const observer = new IntersectionObserver((entries, currentObserver) => {
        entries.forEach((entry) => {
            if (!entry.isIntersecting) return;
            entry.target.classList.add("is-visible");
            currentObserver.unobserve(entry.target);
        });
    }, { threshold: 0.16 });

    revealables.forEach((element) => observer.observe(element));
}

function setupYear() {
    const target = document.getElementById("currentYear");
    if (target) target.textContent = new Date().getFullYear();
}

